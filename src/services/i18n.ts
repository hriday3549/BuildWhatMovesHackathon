const originalText = new WeakMap<Text, string>()
const originalAttributes = new WeakMap<Element, Record<string, string>>()

function translateValue(value: string) {
  if (translations[value]) return translations[value]
  let translated = value
  Object.entries(translations).sort(([first], [second]) => second.length - first.length).forEach(([source, target]) => { translated = translated.split(source).join(target) })
  return translated
}

export function installPageLanguage(language: 'en' | 'hi') {
  const root = document.body
  const attributes = ['placeholder', 'title', 'aria-label']
  const update = (node: Node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      const text = node as Text
      const original = originalText.get(text) ?? text.data
      originalText.set(text, original)
      text.data = language === 'hi' ? translateValue(original) : original
      return
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return
    const element = node as Element
    if (element.tagName === 'SCRIPT' || element.tagName === 'STYLE') return
    const saved = originalAttributes.get(element) ?? {}
    attributes.forEach(attribute => {
      const value = element.getAttribute(attribute)
      if (value !== null) { saved[attribute] ??= value; element.setAttribute(attribute, language === 'hi' ? translateValue(saved[attribute]) : saved[attribute]) }
    })
    originalAttributes.set(element, saved)
    node.childNodes.forEach(update)
  }
  update(root)
  document.documentElement.lang = language === 'hi' ? 'hi' : 'en'
  const observer = new MutationObserver(records => records.forEach(record => {
    if (record.type === 'characterData' || record.type === 'attributes') update(record.target)
    record.addedNodes.forEach(update)
  }))
  observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: attributes })
  return () => observer.disconnect()
}
